/**
 * Pick the agents that should handle an objective.
 *
 * A keyword pre-filter narrows the registry, then the model chooses from that
 * shortlist. Keeping the pre-filter deterministic makes routing explainable and
 * keeps the router prompt small; the model still owns the final decision.
 */
export async function selectAgents(ctx: CosContext, objective: string, limit = 3) {
  const agents = await prisma.aIAgent.findMany({
    where: { businessId: ctx.businessId, status: "ACTIVE" },
    select: { id: true, key: true, name: true, role: true, description: true, capabilities: true },
  });
  if (agents.length === 0) return [];

  const haystack = objective.toLowerCase();
  const scored = agents
    .map((agent) => {
      const hints = AGENT_ROUTING_HINTS[agent.key] ?? [];
      const hits = hints.filter((hint) => haystack.includes(hint)).length;
      const capabilityHits = agent.capabilities.filter((capability) =>
        haystack.includes(capability.toLowerCase())
      ).length;
      return { agent, score: hits * 2 + capabilityHits };
    })
    .sort((a, b) => b.score - a.score);

  const matched = scored.filter((entry) => entry.score > 0).slice(0, limit);
  if (matched.length > 0) return matched.map((entry) => entry.agent);

  // No keyword signal — fall back to strategy, which is the safe generalist.
  const strategy = agents.find((agent) => agent.key === "strategy");
  return strategy ? [strategy] : [agents[0]];
}

export async function runAgent(
  ctx: CosContext,
  options: { agentKey: string; objective: string; conversationId?: string }
) {
  const agent = await prisma.aIAgent.findUnique({
    where: { businessId_key: { businessId: ctx.businessId, key: options.agentKey } },
  });
  if (!agent) throw notFound(`No agent with key "${options.agentKey}".`);
  if (agent.status !== "ACTIVE") {
    throw new AppError(`The ${agent.name} is disabled.`, { status: 409, code: "agent_disabled" });
  }

  const execution = await prisma.agentExecution.create({
    data: {
      businessId: ctx.businessId,
      agentId: agent.id,
      conversationId: options.conversationId,
      requestedById: ctx.userId,
      objective: options.objective,
      status: "RUNNING",
    },
  });

  const startedAt = Date.now();
  try {
    const contextBlock = await buildContextBlock(ctx);
    const system = `${agent.systemPrompt}\n\n---\n${contextBlock}`;
    const model = resolveModel(agent.model);

    const result = await runLoop(ctx, {
      system,
      messages: [{ role: "user", content: options.objective }],
      tools: toolsForContext(ctx, agent.allowedTools.length > 0 ? agent.allowedTools : undefined),
      model,
      agentKey: agent.key,
      conversationId: options.conversationId,
      executionId: execution.id,
      purpose: "agent_execution",
    });

    const output = result.text || "The agent produced no output.";
    const finished = await prisma.agentExecution.update({
      where: { id: execution.id },
      data: {
        status: "SUCCEEDED",
        output,
        durationMs: Date.now() - startedAt,
        finishedAt: new Date(),
        contextSummary: result.toolCalls.map((call) => call.name).join(", ") || null,
      },
    });

    await recordAudit(ctx, {
      action: "agent.run",
      entityType: "agent_execution",
      entityId: execution.id,
      actorKind: "AGENT",
      actorLabel: agent.name,
      detail: { agentKey: agent.key, tools: result.toolCalls.map((call) => call.name) },
    });

    return { execution: finished, agent, output, toolCalls: result.toolCalls };
  } catch (error) {
    const message = error instanceof AppError ? error.message : "The agent run failed.";
    await prisma.agentExecution.update({
      where: { id: execution.id },
      data: {
        status: "FAILED",
        error: message,
        durationMs: Date.now() - startedAt,
        finishedAt: new Date(),
      },
    });
    await recordAudit(ctx, {
      action: "agent.run",
      entityType: "agent_execution",
      entityId: execution.id,
      result: "FAILURE",
      actorKind: "AGENT",
      actorLabel: agent.name,
      detail: { message },
    });
    throw error;
  }
}

/**
 * Multi-agent orchestration: route the objective, run the selected agents, then
 * have the Chief of Staff combine their outputs into one recommendation.
 *
 * Agents run sequentially rather than in parallel so a burst of requests cannot
 * trip the provider's rate limit mid-orchestration.
 */
export async function orchestrate(
  ctx: CosContext,
  options: { objective: string; conversationId?: string; agentKey?: string }
) {
  const selected = options.agentKey
    ? [{ key: options.agentKey, name: options.agentKey, role: "", description: "", id: "", capabilities: [] }]
    : await selectAgents(ctx, options.objective);

  if (selected.length === 0) {
    throw new AppError("No AI agents are registered yet. Seed the agent registry in Settings.", {
      status: 409,
      code: "no_agents",
    });
  }

  const outputs: { agentKey: string; agentName: string; output: string }[] = [];
  for (const candidate of selected) {
    const run = await runAgent(ctx, {
      agentKey: candidate.key,
      objective: options.objective,
      conversationId: options.conversationId,
    });
    outputs.push({ agentKey: run.agent.key, agentName: run.agent.name, output: run.output });
  }

  if (outputs.length === 1) {
    return { agents: outputs, synthesis: outputs[0].output };
  }

  const anthropic = getAnthropic();
  const model = resolveModel();
  const brief = outputs
    .map((entry) => `## ${entry.agentName}\n${entry.output}`)
    .join("\n\n");

  let synthesis: string;
  try {
    const response = await anthropic.messages.create({
      model,
      max_tokens: MAX_TOKENS,
      system: `${CHIEF_OF_STAFF_PROMPT}\n\nYou are combining specialist agent outputs into one executive recommendation. Resolve contradictions explicitly, drop duplication, and end with a single prioritised action list. Do not invent facts none of the agents provided.`,
      thinking: { type: "adaptive" },
      output_config: { effort: resolveEffort() },
      messages: [
        {
          role: "user",
          content: `Objective: ${options.objective}\n\nSpecialist agent outputs:\n\n${brief}`,
        },
      ],
    });
    await recordAiUsage(ctx, {
      model,
      purpose: "orchestration_synthesis",
      usage: response.usage,
      conversationId: options.conversationId,
    });
    synthesis = textFromContent(response.content);
  } catch (error) {
    throw toAiError(error);
  }

  await recordAudit(ctx, {
    action: "ai.orchestrate",
    detail: { objective: options.objective.slice(0, 200), agents: outputs.map((o) => o.agentKey) },
  });

  return { agents: outputs, synthesis };
}
