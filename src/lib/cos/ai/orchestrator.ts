export async function ensureConversation(ctx: CosContext, conversationId?: string) {
  if (conversationId) {
    const existing = await prisma.conversation.findUnique({ where: { id: conversationId } });
    if (!existing || existing.businessId !== ctx.businessId) throw notFound("That conversation could not be found.");
    return existing;
  }
  return prisma.conversation.create({
    data: { businessId: ctx.businessId, userId: ctx.userId, title: "New conversation" },
  });
}

export async function sendChatMessage(
  ctx: CosContext,
  input: { conversationId?: string; message: string }
) {
  const conversation = await ensureConversation(ctx, input.conversationId);

  await prisma.message.create({
    data: { conversationId: conversation.id, role: "USER", content: input.message },
  });

  const history = await prisma.message.findMany({
    where: { conversationId: conversation.id, role: { in: ["USER", "ASSISTANT"] } },
    orderBy: { createdAt: "asc" },
    take: 30,
    select: { role: true, content: true },
  });

  const contextBlock = await buildContextBlock(ctx);
  const system = `${CHIEF_OF_STAFF_PROMPT}\n\n---\n${contextBlock}`;

  const messages: Turn[] = history.map((message) => ({
    role: message.role === "USER" ? ("user" as const) : ("assistant" as const),
    content: message.content,
  }));

  const model = resolveModel();
  const result = await runLoop(ctx, {
    system,
    messages,
    tools: toolsForContext(ctx),
    model,
    conversationId: conversation.id,
    purpose: "chief_of_staff_chat",
  });

  const reply = result.text || "I could not produce an answer for that. Try rephrasing the question.";

  await prisma.message.create({
    data: {
      conversationId: conversation.id,
      role: "ASSISTANT",
      content: reply,
      toolCalls: result.toolCalls.length > 0 ? (result.toolCalls as never) : undefined,
    },
  });

  // Name the conversation from its first exchange so the history list is usable.
  if (conversation.title === "New conversation") {
    await prisma.conversation.update({
      where: { id: conversation.id },
      data: { title: input.message.slice(0, 70) },
    });
  } else {
    await prisma.conversation.update({
      where: { id: conversation.id },
      data: { updatedAt: new Date() },
    });
  }

  await recordAudit(ctx, {
    action: "ai.chat",
    entityType: "conversation",
    entityId: conversation.id,
    detail: { tools: result.toolCalls.map((call) => call.name) },
  });

  return { conversationId: conversation.id, reply, toolCalls: result.toolCalls };
}

